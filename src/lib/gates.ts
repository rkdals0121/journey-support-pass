export const gateArea = (gate: number): Area => (gate < 100 ? "T1" : gate < 200 ? "CONCOURSE" : "T2");
export const isGate = (gate: number): boolean => gate in GATE_XY;

// 걷는 거리(m). 탑승구 번호 순서로 이웃한 탑승구끼리(건물을 따라 이어진다)와, SHORTCUT_M 안쪽 탑승구끼리(통로를 건넌다,
// 직선 × SHORTCUT_DETOUR)를 길로 보고 가장 짧은 길을 잰다. 직선거리로 재면 초승달 모양 터미널에서 계류장을 가로지른다.
// ponytail: 실제 통로망이 아니라 탑승구 좌표로 만든 근사다. 공항 실내 지도를 받으면 그 통로망으로 바꾼다.
const SHORTCUT_M = 250;
const SHORTCUT_DETOUR = 1.3;
let walkTable: Map<number, Map<number, number>> | undefined;

/** 같은 구역 두 탑승구 사이 걷는 거리(m). 구역이 다르면 Infinity. */
export function walkM(a: number, b: number): number {
  walkTable ??= buildWalk();
  return walkTable.get(a)?.get(b) ?? Infinity;
}

function buildWalk() {
  const table = new Map<number, Map<number, number>>();
  for (const area of ["T1", "CONCOURSE", "T2"] as Area[]) {
    const gs = Object.keys(GATE_XY).map(Number).filter((g) => gateArea(g) === area).sort((a, b) => a - b);
    const line = (i: number, j: number) => Math.hypot(GATE_XY[gs[i]][0] - GATE_XY[gs[j]][0], GATE_XY[gs[i]][1] - GATE_XY[gs[j]][1]);
    const d = gs.map((_, i) => gs.map((_, j) => (i === j ? 0 : Infinity)));
    for (let i = 0; i < gs.length; i++)
      for (let j = i + 1; j < gs.length; j++) {
        const w = j === i + 1 ? line(i, j) : line(i, j) < SHORTCUT_M ? line(i, j) * SHORTCUT_DETOUR : Infinity;
        d[i][j] = d[j][i] = Math.min(d[i][j], w);
      }
    for (let k = 0; k < gs.length; k++)
      for (let i = 0; i < gs.length; i++)
        for (let j = 0; j < gs.length; j++) if (d[i][k] + d[k][j] < d[i][j]) d[i][j] = d[i][k] + d[k][j];
    gs.forEach((g, i) => table.set(g, new Map(gs.map((h, j) => [h, d[i][j]]))));
  }
  return table;
}
