/** 화면에 쓸 문구 묶음. easy 가 참이면 쉬운 말이 있는 문구는 쉬운 말로 바꾼다. */
export function textOf(lang: Lang, easy = false): Text {
  const base = lang === "en" ? en : ko;
  if (!easy) return base;
  return { ...base, ...(lang === "en" ? enEasy : koEasy) };
}

